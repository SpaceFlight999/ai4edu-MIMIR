import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { wordmarkArt, WORDMARK_INK_CSS } from './tone.mjs';
const root = name => new URL(name, import.meta.url);
const png = await readFile(root('./mimir-original-transparent.png'));
const data = 'data:image/png;base64,' + png.toString('base64');
const art = `<svg xmlns="http://www.w3.org/2000/svg" width="960" height="464" viewBox="0 0 960 464" role="img" aria-label="MIMIR 智慧之泉"><style>${WORDMARK_INK_CSS}</style><defs>${wordmarkArt('mimir-static',data)}</defs><use href="#mimir-static-art"/></svg>`;
await mkdir(root('./svg/'), { recursive: true });
// Keep legacy export paths, all with the selected dark steel-blue metal tone.
for (const name of ['primary', 'night', 'mono', 'white']) await writeFile(root('./svg/mimir-' + name + '.svg'), art);
await writeFile(root('./artwork.svg'), art);
await writeFile(root('./preview.svg'), art);
const source = (await readFile(root('./tone.mjs'), 'utf8')).replace(/^export /gm, '') + '\n' + await readFile(root('./motion-runtime.mjs'), 'utf8');
await writeFile(root('./interactive.mjs'), '// Generated by build.mjs from motion-runtime.mjs and the existing transparent PNG.\nconst WORDMARK_IMAGE = ' + JSON.stringify(data) + ';\n' + source);
console.log('Built transparent artwork and motif animation component.');
