// Existing research directory controls, exercised only against the caller's isolated fixture.
import assert from 'node:assert/strict'
import {openResearchChat,sendResearchChat,readNewResearchReply} from './research-chat-driver.mjs'

export async function runSessionManagement({browser,reply,restart,checks}) {
  const row = title => `[...document.querySelectorAll('.mimir-session-row')].find(row=>row.querySelector('.mimir-session-open')?.title===${JSON.stringify(title)})`
  const titles = () => browser.evaluate("[...document.querySelectorAll('.mimir-session-open')].map(node=>node.title)")
  const set = async(selector,value) => assert.equal(await browser.evaluate(`(()=>{const el=document.querySelector(${JSON.stringify(selector)});if(!el)return false;Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,${JSON.stringify(value)});el.dispatchEvent(new Event('input',{bubbles:true}));return true})()`),true,'Missing existing input: '+selector)
  const click = async(expression) => assert.equal(await browser.evaluate(`(()=>{const el=${expression};if(!el||el.disabled)return false;el.click();return true})()`),true,'Missing enabled existing control')
  const button = label => `[...document.querySelectorAll('[role=dialog] button')].find(node=>node.textContent.trim()===${JSON.stringify(label)})`
  const rename = async(title,value,confirm) => {
    await click(`${row(title)}?.querySelector('.mimir-session-rename')`)
    await browser.waitFor('Boolean(document.querySelector("input[aria-label=会话名称]"))')
    await set('input[aria-label=会话名称]',value)
    await click(button(confirm?'重命名':'取消'))
    await browser.waitFor('!document.querySelector("input[aria-label=会话名称]")')
  }
  await browser.waitFor('Boolean(document.querySelector(".mimir-session-open[aria-current=page]"))')
  const initial=await browser.evaluate('document.querySelector(".mimir-session-open[aria-current=page]").title')
  await rename(initial,'取消后不能留下此名称',false)
  assert.ok((await titles()).includes(initial));assert.ok(!(await titles()).includes('取消后不能留下此名称'))
  await rename(initial,'合成会话甲：单位核对',true)
  await browser.waitFor(`${row('合成会话甲：单位核对')}!==undefined`)
  checks.push('session rename cancel leaves title intact; confirmed rename updates the actual directory row')
  await click(`${row('合成会话甲：单位核对')}?.querySelector('[aria-label="置顶会话"]')`)
  await browser.waitFor(`Boolean(${row('合成会话甲：单位核对')}?.querySelector('[aria-label="取消置顶"]'))`)
  await openResearchChat(browser)
  await browser.waitFor('document.querySelector(".mimir-session-open[aria-current=page]")?.title==="新研究"&&document.querySelectorAll(".hWmORq_body").length===0')
  await browser.evaluate('new Promise(done=>requestAnimationFrame(()=>requestAnimationFrame(done)))')
  const before=await sendResearchChat(browser,'合成第二研究：仅验证会话管理，不调用工具。')
  assert.equal(await readNewResearchReply(browser,before,30000),reply)
  const second=await browser.evaluate('document.querySelector(".mimir-session-open[aria-current=page]").title')
  await rename(second,'合成会话乙：独立记录',true)
  assert.ok((await titles()).includes('合成会话甲：单位核对'));assert.ok((await titles()).includes('合成会话乙：独立记录'))
  checks.push('new research creates a separate completed conversation; first session remains pinned')
  await set('.mimir-directory-search input','合成会话甲')
  await browser.waitFor(`${row('合成会话甲：单位核对')}!==undefined&&${row('合成会话乙：独立记录')}===undefined`)
  await set('.mimir-directory-search input','确定不存在的合成名称')
  await browser.waitFor('document.querySelectorAll(".mimir-session-row").length===0')
  await set('.mimir-directory-search input','')
  await browser.waitFor(`${row('合成会话乙：独立记录')}!==undefined`)
  checks.push('research title search filters matching rows, unmatched query empties results, clearing restores both sessions')
  await click(`${row('合成会话甲：单位核对')}?.querySelector('[aria-label="取消置顶"]')`)
  await browser.waitFor(`Boolean(${row('合成会话甲：单位核对')}?.querySelector('[aria-label="置顶会话"]'))`)
  await click(`${row('合成会话甲：单位核对')}?.querySelector('[aria-label="置顶会话"]')`)
  await browser.waitFor(`Boolean(${row('合成会话甲：单位核对')}?.querySelector('[aria-label="取消置顶"]'))`)
  checks.push('pin and unpin update the actual row action without modifying either conversation')
  await click(`${row('合成会话甲：单位核对')}?.querySelector('[aria-label="归档会话"]')`)
  await browser.waitFor(`${row('合成会话甲：单位核对')}===undefined`)
  await click('document.querySelector(".mimir-directory-archive")')
  await browser.waitFor(`${row('合成会话甲：单位核对')}!==undefined`)
  assert.equal(await browser.evaluate(`${row('合成会话甲：单位核对')}.querySelector('.mimir-session-open').disabled`),true)
  await click(`${row('合成会话甲：单位核对')}?.querySelector('[aria-label="取消归档"]')`)
  await browser.waitFor(`${row('合成会话甲：单位核对')}===undefined`)
  await click('document.querySelector(".mimir-directory-archive")')
  await browser.waitFor(`${row('合成会话甲：单位核对')}!==undefined`)
  await click(`${row('合成会话甲：单位核对')}?.querySelector('.mimir-session-open')`)
  await browser.waitFor('Boolean(document.querySelector(".hWmORq_body"))')
  assert.equal(await browser.evaluate('document.querySelector(".hWmORq_body").innerText'),reply)
  checks.push('archive removes the active row; archived directory prevents opening; restore recovers the original assistant text')
  // Native archive intentionally removes the pin; restoring does not silently re-pin.
  await browser.waitFor(`Boolean(${row('合成会话甲：单位核对')}?.querySelector('[aria-label="置顶会话"]'))`)
  await click(`${row('合成会话甲：单位核对')}?.querySelector('[aria-label="置顶会话"]')`)
  await browser.waitFor(`Boolean(${row('合成会话甲：单位核对')}?.querySelector('[aria-label="取消置顶"]'))`)
  await browser.send('Page.reload')
  await browser.waitFor('Boolean(document.querySelector(".mimir-product-nav button[aria-label=研究]"))')
  await browser.evaluate('document.querySelector(".mimir-product-rail-end button[aria-label=展开侧栏]")?.click();document.querySelector(".mimir-product-nav button[aria-label=研究]").click()')
  await browser.waitFor(`Boolean(${row('合成会话甲：单位核对')}?.querySelector('[aria-label="取消置顶"]'))`)
  checks.push('restored conversation may be pinned again; refresh preserves confirmed title and new pin state')
  await restart()
  await browser.waitFor('Boolean(document.querySelector(".mimir-product-nav button[aria-label=研究]"))')
  await browser.evaluate('document.querySelector(".mimir-product-rail-end button[aria-label=展开侧栏]")?.click();document.querySelector(".mimir-product-nav button[aria-label=研究]").click()')
  await browser.waitFor(`Boolean(${row('合成会话甲：单位核对')}?.querySelector('[aria-label="取消置顶"]'))`)
  assert.ok((await titles()).includes('合成会话乙：独立记录'))
  await click(`${row('合成会话甲：单位核对')}?.querySelector('.mimir-session-open')`)
  await browser.waitFor('Boolean(document.querySelector(".hWmORq_body"))')
  assert.equal(await browser.evaluate('document.querySelector(".hWmORq_body").innerText'),reply)
  checks.push('normal native-host restart preserves both names, pin state, restored session and assistant history')
}
