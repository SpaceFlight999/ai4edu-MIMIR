async function click(text, scope = '.mg-app', contains = false) {
  const success = await browser.evaluate(`(() => { const button=[...document.querySelectorAll(${JSON.stringify(scope + ' button')})].find(el=>${contains ? 'el.textContent.includes' : 'el.textContent.trim() ==='}${contains ? '(' : ' '}${JSON.stringify(text)}${contains ? ')' : ''});if(!button || button.disabled)return false;button.click();return true;})()`)
  assert.equal(success, true, 'Missing or disabled button: ' + text)
  await new Promise(resolve => setTimeout(resolve, 120))
}
