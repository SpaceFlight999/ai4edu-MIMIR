async function click(label, scope = '.mg-app', contains = false) {
  assert.equal(await browser.evaluate(`(() => {const el=[...document.querySelectorAll(${JSON.stringify(scope + ' button')})].find(el=>${contains ? 'el.textContent.includes(' + JSON.stringify(label) + ')' : 'el.textContent.trim()===' + JSON.stringify(label)});if(!el||el.disabled)return false;el.click();return true})()`), true, 'Button unavailable: ' + label)
  await new Promise(resolve => setTimeout(resolve, 100))
  await browser.waitFor("!document.querySelector('.mg-busy')")
}
async function change(selector, value) {
  assert.equal(await browser.evaluate(`(() => {const el=document.querySelector(${JSON.stringify(selector)});if(!el||el.disabled)return false;Object.getOwnPropertyDescriptor(el.tagName==='TEXTAREA'?HTMLTextAreaElement.prototype:HTMLSelectElement.prototype,'value').set.call(el,${JSON.stringify(value)});el.dispatchEvent(new Event(el.tagName==='TEXTAREA'?'input':'change',{bubbles:true}));return true})()`), true, 'Input unavailable: ' + selector)
  await new Promise(resolve => setTimeout(resolve, 100))
}
